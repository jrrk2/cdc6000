#!/usr/bin/env python3
"""genmem.py out.v image.img [image.img ...] -- the core's 64K x 60 bit memory as explicit RAMB36E1s, initialised from images.

Inference of a 4 Mbit RAM with initial contents made Vivado take hours; this writes the RAM as 2 banks x 60 bit slices of
RAMB36E1 (32K x 1 each, 120 in all) with the images in INIT_xx parameters; port A reads and writes, port B reads (the instruction fetch of cdc6000_sb), as ~/bytecode/tools/gen_rom_bram.py does for the
bytecode core.  Port A reads and writes (read first); an image line is "<octal address> <octal word>".
"""
import sys

DEPTH = 32768
W = 60

def main():
    out = sys.argv[1]
    mem = {}
    for f in sys.argv[2:]:
        for l in open(f):
            a, w = l.split(); mem[int(a, 8)] = int(w, 8)
    if mem and max(mem) >= 2 * DEPTH:
        sys.exit('image does not fit 64K words')
    o = ['// Generated by genmem.py (%d words). Do not edit.' % len(mem), '`default_nettype none',
         'module cdc_ram_bram (', '\tinput  wire        clk,', '\tinput  wire        en,', '\tinput  wire        we,',
         '\tinput  wire [15:0] addr,', '\tinput  wire [59:0] din,', '\toutput wire [59:0] dout,',
         '\tinput  wire [15:0] iaddr,       // port B: read only, for the instruction stack', '\toutput wire [59:0] idout', ');']
    for bank in range(2):
        for b in range(W):
            o.append('\twire [31:0] do_%d_%d;' % (bank, b))
            o.append('\twire [31:0] dob_%d_%d;' % (bank, b))
    o.append('\treg bank_q, ibank_q;')
    o.append('\talways @(posedge clk) begin if (en) bank_q <= addr[15]; ibank_q <= iaddr[15]; end')
    for bank in range(2):
        for bit in range(W):
            init = []
            for ln in range(128):
                v = 0
                for j in range(256):
                    a = bank * DEPTH + ln * 256 + j
                    if a in mem and (mem[a] >> bit) & 1:
                        v |= 1 << j
                if v: init.append('.INIT_%02X(256\'h%064x)' % (ln, v))
            params = ', '.join(['.READ_WIDTH_A(1)', '.READ_WIDTH_B(1)', '.WRITE_WIDTH_A(1)', '.WRITE_WIDTH_B(1)',
                                '.RAM_MODE("TDP")', '.DOA_REG(0)', '.DOB_REG(0)', '.WRITE_MODE_A("READ_FIRST")',
                                '.SIM_DEVICE("7SERIES")'] + init)
            sel = "(addr[15] == 1'b%d)" % bank
            o.append('\tRAMB36E1 #(%s) r%d_%d (' % (params, bank, bit))
            o.append('\t\t.CLKARDCLK(clk), .CLKBWRCLK(clk),')
            o.append("\t\t.ENARDEN(en && %s), .ENBWREN(iaddr[15] == 1'b%d)," % (sel, bank))
            o.append("\t\t.REGCEAREGCE(1'b0), .REGCEB(1'b0), .RSTRAMARSTRAM(1'b0), .RSTRAMB(1'b0), .RSTREGARSTREG(1'b0), .RSTREGB(1'b0),")
            o.append("\t\t.ADDRARDADDR({1'b0, addr[14:0]}), .ADDRBWRADDR({1'b0, iaddr[14:0]}),")
            o.append("\t\t.DIADI({31'b0, din[%d]}), .DIPADIP(4'b0), .DIBDI(32'b0), .DIPBDIP(4'b0)," % bit)
            o.append("\t\t.WEA({4{we && %s}}), .WEBWE(8'b0)," % sel)
            o.append('\t\t.DOADO(do_%d_%d), .DOPADOP(), .DOBDO(dob_%d_%d), .DOPBDOP(),' % (bank, bit, bank, bit))
            o.append("\t\t.CASCADEINA(1'b0), .CASCADEINB(1'b0), .CASCADEOUTA(), .CASCADEOUTB(),")
            o.append("\t\t.INJECTDBITERR(1'b0), .INJECTSBITERR(1'b0), .DBITERR(), .SBITERR(), .ECCPARITY(), .RDADDRECC());")
    # the same contents as set_property lines, for swap.tcl: patches a routed design without synthesis or P&R
    t = ['# Generated by genmem.py. INIT of every RAMB36E1 of the memory.']
    for bank in range(2):
        for bit in range(W):
            for ln in range(128):
                v = 0
                for j in range(256):
                    a = bank * DEPTH + ln * 256 + j
                    if a in mem and (mem[a] >> bit) & 1:
                        v |= 1 << j
                t.append('I r%d_%d %02X 256\'h%064x' % (bank, bit, ln, v))
    open(out[:-2] + '.init.tcl' if out.endswith('.v') else out + '.init.tcl', 'w').write('\n'.join(t) + '\n')
    for bit in range(W):
        o.append('\tassign dout[%d] = bank_q ? do_1_%d[0] : do_0_%d[0];' % (bit, bit, bit))
        o.append('\tassign idout[%d] = ibank_q ? dob_1_%d[0] : dob_0_%d[0];' % (bit, bit, bit))
    o += ['endmodule', '`default_nettype wire']
    open(out, 'w').write('\n'.join(o) + '\n')
    print('%s: %d words in 120 RAMB36E1' % (out, len(mem)))

main()
