#!/usr/bin/env python3
"""gendisk.py out.v disk.hex KB [name=path ...] -- the ramdisk: KB kilobytes of RAMB36E1 (4K x 8 each, KB/4 of them),
initialised with a file system holding the files given, as explicit primitives (cdc_disk_bram, like genmem.py's memory),
and the same bytes as disk.hex for the simulation stand-in (sim/cdc_disk_sim.v).  KB = 0 makes an empty module (no disk).

The file system (nfs/nfslib.pas, RD*): blocks of 1024 bytes.
  block 0      header: "CD", entries (2), first free block (2), blocks (2), entries at build (2), first free at build (2);
               from byte 16 the entries, 16 bytes each: name (10, lower case, 0 padded), first block (2, 65535: none),
               length (3), deleted (1)
  blocks 1..2  the chain: 2 bytes per block, the next block of the file, 65535 at its end
  blocks 3..   the data.  Blocks are only ever taken from the free end (append only); `compile` on the ramdisk and
               `ram reset` put the entries and the free pointer back to the values at build.
All numbers little end.  Names are at most ten characters (the entry) and are matched whole.
"""
import sys

BLK = 1024

def main():
    out, hexf, kb = sys.argv[1], sys.argv[2], int(sys.argv[3])
    nblk = kb
    img = bytearray(kb * 1024)
    entries = []
    fat = [0xFFFF] * nblk
    free = 3 if nblk > 3 else nblk
    for spec in sys.argv[4:]:
        name, path = spec.split('=', 1)
        if len(name) > 10:
            sys.exit('name longer than ten characters: ' + name)
        data = open(path, 'rb').read()
        first, prev = 0xFFFF, None
        for off in range(0, len(data), BLK):
            if free >= nblk:
                sys.exit('the files do not fit %d KB' % kb)
            b = free; free += 1
            img[b * BLK:b * BLK + len(data[off:off + BLK])] = data[off:off + BLK]
            if prev is None: first = b
            else: fat[prev] = b
            prev = b
        entries.append((name, first, len(data)))
    if len(entries) > 63:
        sys.exit('more than 63 files')
    if nblk:
        hdr = img
        hdr[0:2] = b'CD'
        for pos, v in ((2, len(entries)), (4, free), (6, nblk), (8, len(entries)), (10, free)):
            hdr[pos:pos + 2] = v.to_bytes(2, 'little')
        for i, (name, first, ln) in enumerate(entries):
            e = 16 + 16 * i
            hdr[e:e + 10] = name.encode('ascii').ljust(10, b'\0')
            hdr[e + 10:e + 12] = first.to_bytes(2, 'little')
            hdr[e + 12:e + 15] = ln.to_bytes(3, 'little')
            hdr[e + 15] = 0
        for b in range(nblk):
            img[BLK + 2 * b:BLK + 2 * b + 2] = fat[b].to_bytes(2, 'little')
    with open(hexf, 'w') as h:
        for i in range(0, len(img), 32):
            h.write(' '.join('%02x' % x for x in img[i:i + 32]) + '\n')
    n = kb // 4                                  # RAMB36E1s of 4096 bytes
    o = ['// Generated by gendisk.py (%d KB, %d files). Do not edit.' % (kb, len(entries)), '`default_nettype none',
         'module cdc_disk_bram (', '\tinput  wire        clk,', '\tinput  wire        we,', '\tinput  wire [19:0] addr,',
         '\tinput  wire [7:0]  din,', '\toutput reg  [7:0]  dout,       // the byte at addr, two clocks after addr changes',
         '\toutput wire [15:0] size_kb', ');', '\tassign size_kb = 16\'d%d;' % kb]
    if n == 0:
        o += ['\talways @(posedge clk) dout <= 8\'d0;']
    else:
        o.append('\twire [31:0] do [0:%d];' % (n - 1))
        for k in range(n):
            init = []
            for ln in range(128):
                v = int.from_bytes(img[k * 4096 + ln * 32:k * 4096 + ln * 32 + 32], 'little')
                if v: init.append('.INIT_%02X(256\'h%064x)' % (ln, v))
            params = ', '.join(['.READ_WIDTH_A(9)', '.WRITE_WIDTH_A(9)', '.READ_WIDTH_B(0)', '.WRITE_WIDTH_B(0)',
                                '.RAM_MODE("TDP")', '.DOA_REG(0)', '.DOB_REG(0)', '.WRITE_MODE_A("READ_FIRST")',
                                '.SIM_DEVICE("7SERIES")'] + init)
            o.append('\tRAMB36E1 #(%s) d%d (' % (params, k))
            o.append('\t\t.CLKARDCLK(clk), .CLKBWRCLK(clk), .ENARDEN(1\'b1), .ENBWREN(1\'b0),')
            o.append("\t\t.REGCEAREGCE(1'b0), .REGCEB(1'b0), .RSTRAMARSTRAM(1'b0), .RSTRAMB(1'b0), .RSTREGARSTREG(1'b0), .RSTREGB(1'b0),")
            o.append("\t\t.ADDRARDADDR({1'b0, addr[11:0], 3'b000}), .ADDRBWRADDR(16'b0),")
            o.append("\t\t.DIADI({24'b0, din}), .DIPADIP(4'b0), .DIBDI(32'b0), .DIPBDIP(4'b0),")
            o.append("\t\t.WEA({4{we && addr[19:12] == 8'd%d}}), .WEBWE(8'b0)," % k)
            o.append('\t\t.DOADO(do[%d]), .DOPADOP(), .DOBDO(), .DOPBDOP(),' % k)
            o.append("\t\t.CASCADEINA(1'b0), .CASCADEINB(1'b0), .CASCADEOUTA(), .CASCADEOUTB(),")
            o.append("\t\t.INJECTDBITERR(1'b0), .INJECTSBITERR(1'b0), .DBITERR(), .SBITERR(), .ECCPARITY(), .RDADDRECC());")
        o += ['\treg [7:0] sel_q;', '\talways @(posedge clk) begin sel_q <= addr[19:12]; dout <= do[sel_q][7:0]; end']
    o += ['endmodule', '`default_nettype wire']
    open(out, 'w').write('\n'.join(o) + '\n')
    print('%s: %d KB in %d RAMB36E1, %d files, %d KB used' % (out, kb, n, len(entries), free))

main()
